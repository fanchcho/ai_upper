import fs from 'node:fs';
import {createRequire} from 'node:module';
const devaRoot=process.argv[2];
if (!devaRoot) throw new Error('Usage: node scripts/parity/build_humation.mjs <deva-root>');
const require=createRequire(devaRoot+'/package.json');
const esbuild=require('esbuild');
const src=fs.readFileSync('scripts/parity/gen_avatars.mjs','utf8');
let body=src.slice(src.indexOf('const HAIR_TONES'),src.indexOf('// 用户头像：'));
const original=fs.readFileSync(devaRoot+'/apps/desktop/src/renderer/src/components/humation.tsx','utf8');
const shapeSource=fs.readFileSync(devaRoot+'/apps/desktop/src/shared/avatar-shape.ts','utf8');
const helpers=original.slice(original.indexOf('type Pt ='),original.indexOf('/** 形状的单位路径'));
const mapper=original.slice(original.indexOf('type Box ='),original.indexOf('/* ─────────────────────────────── 规格解析'));
const parser=original.slice(original.indexOf('function pickStrings'),original.indexOf('/** AvatarSpec →'));
body=body.slice(0,body.indexOf('const CIRCLE')) + helpers + mapper + parser + body.slice(body.indexOf('const POP_BOX'));
body=body.replace(/function hashSeed[\s\S]*?\n}\n/,'');
body=body.replaceAll('mapPath(box)','mapPath(resolveShape(seed, spec), box)').replaceAll('selections: spec?.selections','selections: validSelections(spec?.selections)');
body=shapeSource+'\n'+body;
fs.mkdirSync('app/assets/humation',{recursive:true});
await esbuild.build({stdin:{contents:'import {createAvatar, resolvePartId} from "@humation/core";import {humation1} from "@humation/assets-humation-1";'+body+'\nglobalThis.renderHumation=(seed,spec,pop)=>pop?avatarPopSvg(seed,parseAvatarSpec(JSON.stringify(spec))):avatarSvg(seed,parseAvatarSpec(JSON.stringify(spec)));',resolveDir:devaRoot,loader:'ts'},bundle:true,format:'iife',target:'es2017',outfile:'app/assets/humation/runtime.js'});
for(const name of ['core','assets-humation-1'])fs.copyFileSync(devaRoot+'/node_modules/@humation/'+name+'/LICENSE.md','app/assets/humation/'+name+'-LICENSE.md');
